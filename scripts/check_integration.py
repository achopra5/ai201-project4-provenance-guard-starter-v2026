#!/usr/bin/env python3
"""Exercise real cached GPT-2 and the entire Flask pipeline with temporary logs.

Run: HF_HUB_OFFLINE=1 .venv/bin/python scripts/check_integration.py
Saves Unit 8 preparation evidence without overwriting Unit 7 artifacts.
Not discovered by the fast unit suite; no hosted API, attack set, or Unit 8 run.
"""

import json
import argparse
import math
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import app as service
import audit
import config
import detector
from transformers import AutoModelForCausalLM, AutoTokenizer

# All three pieces below are generated by Codex for functional demonstration.
# Their output labels do not establish authorship or detection accuracy.
DEMONSTRATIONS = [
    ("irregular_synthetic", "Hush! Zymurgy, quincunx; xylophagous nuthatches—why did copper, heliotrope, and obsidian orbit my aunt's cracked barometer while a phosphorescent accordion sneezed beneath seventeen upside-down umbrellas? Eh?"),
    ("ordinary_synthetic", "A writing platform needs clear rules. Writers should understand how their work will be reviewed and how to ask for help when the automated system makes a mistake."),
    ("repetitive_synthetic", "The system should provide clear and reliable information for all users. " * 15),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
                        default=config.RESULTS_DIR / "unit8" / "integration_final.json")
    args = parser.parse_args()
    if args.output.exists():
        parser.error(f"{args.output} exists; choose a new output path to preserve evidence.")
    result = {"timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
              "produced_by": "scripts/check_integration.py::main", "checks": [], "submissions": []}
    with tempfile.TemporaryDirectory() as tmp, \
            patch.object(config, "LOG_DIR", Path(tmp)), \
            patch.object(config, "AUDIT_LOG", Path(tmp) / "audit.jsonl"), \
            patch.object(AutoModelForCausalLM, "from_pretrained", wraps=AutoModelForCausalLM.from_pretrained) as load_model, \
            patch.object(AutoTokenizer, "from_pretrained", wraps=AutoTokenizer.from_pretrained) as load_tokenizer:
        client = service.app.test_client()
        assert not client.get("/health").json["detector_loaded"]
        for name, text in DEMONSTRATIONS:
            response = client.post("/submit", json={"text": text, "creator_id": name})
            assert response.status_code == 200, response.json
            body = response.json
            assert all(math.isfinite(body[k]) and 0 <= body[k] <= 1 for k in ("model_score", "style_score", "confidence"))
            assert client.get("/health").json["detector_loaded"]
            result["submissions"].append({"name": name, "origin": "Codex-generated functional demonstration, not a known-human sample.", "text": text, "response": body})
            print(f"{name}: {body['guess']} ({body['confidence']:.6f})")
        load_model.assert_called_once()
        load_tokenizer.assert_called_once()
        result["checks"].append("One model load and one tokenizer load across three real submissions; /health remained loaded.")
        guesses = {item["response"]["guess"] for item in result["submissions"]}
        assert guesses == {"human", "unsure", "ai"}, guesses
        result["checks"].append("All three reader labels reached with real inference on synthetic demonstration text.")
        content_id = result["submissions"][0]["response"]["content_id"]
        reasoning = "Please review this functional demonstration."
        response = client.post("/appeal", json={"content_id": content_id, "reasoning": reasoning})
        assert response.status_code == 200 and response.json["status"] == "under_review"
        events = audit.entries_for(content_id)
        assert events[0]["status"] == "decided" and events[-1]["status"] == "under_review"
        assert events[-1]["reasoning"] == reasoning
        result["appeal"] = response.json
        result["checks"].append("Real submission appealed; exact reasoning and final under_review status persisted alongside original decision.")
        short = client.post("/submit", json={"text": "a", "creator_id": "short"})
        assert short.status_code == 400 and short.json["error"] == "unscorable_text"
        result["checks"].append("One-token input returns JSON 400, with no completed decision.")
        entries = client.get("/log").json["entries"]
        assert len(entries) == 5
        assert sum(e.get("status") == "decided" for e in entries) == 3
        assert sum(e.get("event") == "appeal" for e in entries) == 1
        assert sum(e.get("event") == "rejected" for e in entries) == 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("x", encoding="utf-8") as stream:
        stream.write(json.dumps(result, indent=2, ensure_ascii=False) + "\n")
    print(f"PASS: {len(result['checks'])} real-model integration checks.")


if __name__ == "__main__":
    main()
